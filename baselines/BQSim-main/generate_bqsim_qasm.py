def create_state_transfer_CVtoDV_circuit_qasm(name, num_qubits, num_modes, cutoff, lambda_val=0.29):
    """生成 CV 到 DV 状态转移电路的 QASM 代码"""
    qasm_lines = []
    
    # 添加头部
    qasm_lines.append('// Generated by BQSim QASM generator')
    qasm_lines.append('')
    qasm_lines.append('OPENQASM 2.0;')
