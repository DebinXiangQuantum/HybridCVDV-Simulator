    qasm_lines.append(f'qreg q[{num_qubits}];')
    qasm_lines.append('')
    
    # 生成电路操作
    for j in range(1, num_qubits + 1):
        for q_idx in range(num_qubits):
            qasm_lines.append(f'rx(pi/4) q[{q_idx}];')
