def create_vqe_circuit_qasm(name, num_qubits, num_modes, cutoff, layers=2):
    """生成 VQE 电路的 QASM 代码"""
    qasm_lines = []
    
    # 添加头部
    qasm_lines.append('// Generated by BQSim QASM generator')
    qasm_lines.append('')
    qasm_lines.append('OPENQASM 2.0;')
    qasm_lines.append('include "qelib1.inc";')
    qasm_lines.append('')
    
    # 添加量子寄存器
    for i in range(num_modes):
        num_qubits_per_mode = math.ceil(math.log2(cutoff))
        qasm_lines.append(f'qreg qm{i}[{num_qubits_per_mode}];')
    qasm_lines.append(f'qreg q[{num_qubits}];')
    qasm_lines.append('')
    
    # 生成随机参数
    random.seed(42)
    params = []
    for i in range(layers):
        for qm in range(num_modes):
            params.append(random.uniform(0, 3))
            params.append(random.uniform(0, math.pi))
        for q in range(num_qubits):
            params.append(random.uniform(0, math.pi))
            params.append(random.uniform(0, math.pi))
    
    # 生成电路操作
    param_idx = 0
    for d in range(layers):
        # 添加位移门
        for qm in range(num_modes):
            beta_mag = params[param_idx]
            beta_arg = params[param_idx + 1]
            param_idx += 2
            # 使用 U1 门模拟位移操作
            qasm_lines.append(f'u1({beta_mag}) qm{qm}[0];')
        
        # 添加量子比特旋转
        for q in range(num_qubits):
            theta = params[param_idx]
            phi = params[param_idx + 1]
            param_idx += 2
            qasm_lines.append(f'rx({theta}) q[{q}];')
            qasm_lines.append(f'rz({phi}) q[{q}];')
        
        # 添加 beamsplitter 操作（使用 CNOT 门模拟）
        for qm in range(num_modes - 1):
            qasm_lines.append(f'cx qm{qm}[0],qm{qm+1}[0];')
    
    qasm_lines.append('')  # 添加空行确保文件末尾有换行符
    return '\n'.join(qasm_lines)


def create_jch_circuit_qasm(name, num_qubits, num_modes, cutoff, timesteps=5, J=0.1, omega_r=1.0, omega_q=1.0, g=0.1, tau=0.1):
    """生成 JCH 电路的 QASM 代码"""
    qasm_lines = []
    
    # 添加头部
    qasm_lines.append('// Generated by BQSim QASM generator')
    qasm_lines.append('')
    qasm_lines.append('OPENQASM 2.0;')
    qasm_lines.append('include "qelib1.inc";')
    qasm_lines.append('')
    
    # 添加量子寄存器
    for i in range(num_modes):
        num_qubits_per_mode = math.ceil(math.log2(cutoff))
        qasm_lines.append(f'qreg qm{i}[{num_qubits_per_mode}];')
    qasm_lines.append(f'qreg q[{num_qubits}];')
    qasm_lines.append('')
    
    # 生成电路操作
    for t in range(timesteps):
        # 谐振子旋转
        for i in range(num_modes):
            angle = omega_r * tau
            qasm_lines.append(f'rx({angle}) qm{i}[0];')
        
        # 量子比特旋转
        for i in range(num_qubits):
            angle = omega_q * tau / 2.0
            qasm_lines.append(f'rz({angle}) q[{i}];')
        
        # 耦合操作
        for i in range(min(num_modes - 1, num_qubits)):
            angle = g * tau
            qasm_lines.append(f'cx qm{i}[0],qm{i+1}[0];')
        
        # 谐振子间耦合
        for i in range(num_modes - 1):
            angle = J * tau
            qasm_lines.append(f'cx qm{i}[0],qm{i+1}[0];')
    
    qasm_lines.append('')  # 添加空行确保文件末尾有换行符
    return '\n'.join(qasm_lines)


