def create_qaoa_circuit_qasm(name, num_qubits, num_modes, cutoff, layers=2, s=0.5, a=1.0):
    """生成 QAOA 电路的 QASM 代码"""
    qasm_lines = []
    
    # 添加头部
    qasm_lines.append('// Generated by BQSim QASM generator')
    qasm_lines.append('')
    qasm_lines.append('OPENQASM 2.0;')
    qasm_lines.append('include "qelib1.inc";')
    qasm_lines.append('')
    
    # 添加量子寄存器
    for i in range(num_modes):
        num_qubits_per_mode = math.ceil(math.log2(cutoff))
        qasm_lines.append(f'qreg qm{i}[{num_qubits_per_mode}];')
    qasm_lines.append(f'qreg q[{num_qubits}];')
    qasm_lines.append('')
    
    # 生成电路操作
    for qm in range(num_modes):
        qasm_lines.append(f'u({s},0,0) qm{qm}[0];')
    qasm_lines.append('')
    
    params = [2 * math.pi * (i + 1) / (2 * layers) for i in range(2 * layers)]
    
    for i in range(layers):
        gamma = params[i]
        eta = params[layers + i]
        
        for qm in range(num_modes):
            qasm_lines.append(f'u({a * gamma},0,0) qm{qm}[0];')
        qasm_lines.append('')
        
        for qm in range(num_modes):
            qasm_lines.append(f'u({eta},0,0) qm{qm}[0];')
        qasm_lines.append('')
    
    qasm_lines.append('')  # 添加空行确保文件末尾有换行符
    return '\n'.join(qasm_lines)


def create_qft_circuit_qasm(name, num_qubits, num_modes, cutoff, n=2, a=1, append=1, delta=0.1):
    """生成 QFT 电路的 QASM 代码"""
    qasm_lines = []
    
    # 添加头部
    qasm_lines.append('// Generated by BQSim QASM generator')
    qasm_lines.append('')
    qasm_lines.append('OPENQASM 2.0;')
    qasm_lines.append('include "qelib1.inc";')
    qasm_lines.append('')
    
    # 添加量子寄存器
    for i in range(num_modes):
        num_qubits_per_mode = math.ceil(math.log2(cutoff))
        qasm_lines.append(f'qreg qm{i}[{num_qubits_per_mode}];')
    qasm_lines.append(f'qreg q[{num_qubits}];')
    qasm_lines.append('')
    
    # 生成电路操作
    for qm in range(num_modes):
        qasm_lines.append(f'rx(pi/4.0) qm{qm}[0];')
    qasm_lines.append('')
    
    qasm_lines.append('u(0.29,0,0) qm0[0];')
    qasm_lines.append('')
    
    delta_prime = (2 * math.pi) / (math.pow(2, n + a + append) * delta)
    qasm_lines.append(f'u({delta / 2},0,0) qm0[0];')
    qasm_lines.append('rx(pi/2.0) qm0[0];')
    qasm_lines.append(f'u({-delta_prime / 2},0,0) qm0[0];')
    qasm_lines.append('')
    
    for qm in range(num_modes):
        qasm_lines.append(f'rx(pi/4.0) qm{qm}[0];')
    qasm_lines.append('')
    
    qasm_lines.append('u(0.29,0,0) qm0[0];')
    
    qasm_lines.append('')  # 添加空行确保文件末尾有换行符
    return '\n'.join(qasm_lines)


