def write_qasm_file(qasm_code, filename):
    """将 QASM 代码写入文件"""
    try:
        os.makedirs(OUTPUT_DIR, exist_ok=True)
        with open(filename, 'w') as f:
            f.write(qasm_code)
        return True
    except Exception as e:
        print(f"Error writing QASM file: {e}")
        return False


def process_case(case):
    """处理单个 case，返回 (status, output_name, file_size_or_error)"""
    name = case['name']
    workload = case['workload']
    cutoff = case.get('cutoff', 4)
    num_qubits = case.get('num_qubits', 1)
    num_modes = case.get('num_modes', 1)
    
    output_name = f"{name}.qasm"
    output_path = os.path.join(OUTPUT_DIR, output_name)
    
    if os.path.exists(output_path):
        file_size = os.path.getsize(output_path)
        return ('skip', output_name, file_size)
    

    
    try:
        if workload == 'vqe_circuit':
            layers = case.get('layers', 2)
            qasm_code = create_vqe_circuit_qasm(name, num_qubits, num_modes, cutoff, layers)
        elif workload == 'jch_simulation_circuit':
            timesteps = case.get('timesteps', 5)
            qasm_code = create_jch_circuit_qasm(name, num_qubits, num_modes, cutoff, timesteps)
        elif workload == 'cat_state_circuit':
            alpha = case.get('alpha', 1.0)
            qasm_code = create_cat_state_circuit_qasm(name, num_qubits, num_modes, cutoff, alpha)
        elif workload == 'gkp_state_circuit':
            N_rounds = case.get('N_rounds', 9)
            r = case.get('r', 0.222)
            qasm_code = create_gkp_state_circuit_qasm(name, num_qubits, num_modes, cutoff, N_rounds, r)
        elif workload == 'qaoa_circuit':
            layers = case.get('layers', 2)
            s = case.get('s', 0.5)
            a = case.get('a', 1.0)
            qasm_code = create_qaoa_circuit_qasm(name, num_qubits, num_modes, cutoff, layers, s, a)
        elif workload == 'qft_circuit':
            n = case.get('n', 2)
            a = case.get('a', 1)
            append = case.get('append', 1)
            delta = case.get('delta', 0.1)
            qasm_code = create_qft_circuit_qasm(name, num_qubits, num_modes, cutoff, n, a, append, delta)
        elif workload == 'shors_circuit':
            N = case.get('N', 15)
            m = case.get('m', 5)
            R = case.get('R', 10)
            a = case.get('a', 2)
            delta = case.get('delta', 1.0)
            qasm_code = create_shors_circuit_qasm(name, num_qubits, num_modes, cutoff, N, m, R, a, delta)
        elif workload == 'state_transfer_CVtoDV_circuit':
            lambda_val = case.get('lambda', 0.29)
            qasm_code = create_state_transfer_CVtoDV_circuit_qasm(name, num_qubits, num_modes, cutoff, lambda_val)
        elif workload == 'state_transfer_DVtoCV_circuit':
            lambda_val = case.get('lambda', 0.29)
            qasm_code = create_state_transfer_DVtoCV_circuit_qasm(name, num_qubits, num_modes, cutoff, lambda_val)
        else:
            return ('unknown', output_name, workload)
        
        result = write_qasm_file(qasm_code, output_path)
        if result:
            file_size = os.path.getsize(output_path)
            return ('ok', output_name, file_size)
        else:
            return ('error', output_name, 'write failed')
            
    except Exception as e:
        return ('error', output_name, str(e))


def main():
    json_path = os.path.join(os.path.dirname(__file__), 'sc26_scaling.json')
    
    if not os.path.exists(json_path):
        print(f"Cannot find sc26_scaling.json: {json_path}")
        return 1
    
    with open(json_path, 'r') as f:
        data = json.load(f)
    
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    cases_by_cutoff = {}
    for case in data['cases']:
        cutoff = case.get('cutoff', 4)
        if cutoff not in ALLOWED_CUTOFFS:
            continue
        if cutoff not in cases_by_cutoff:
            cases_by_cutoff[cutoff] = []
        cases_by_cutoff[cutoff].append(case)
    
    sorted_cutoffs = sorted(cases_by_cutoff.keys())
    
    print(f"Found {len(data['cases'])} test cases in sc26_scaling.json")
    print(f"Generating QASM for cutoffs: {sorted_cutoffs}")
    print(f"Output directory: {OUTPUT_DIR}")
    print(f"Using {MAX_WORKERS} parallel workers")
    print("=" * 80)
    
    total_generated = 0
    total_skipped = 0
    errors = []
    
    for cutoff in sorted_cutoffs:
        print(f"\n>>> Processing cutoff = {cutoff}")
        print("-" * 80)
        
        cases = cases_by_cutoff[cutoff]
        
        with concurrent.futures.ProcessPoolExecutor(max_workers=MAX_WORKERS) as executor:
            future_to_case = {executor.submit(process_case, case): case for case in cases}
            
            for future in concurrent.futures.as_completed(future_to_case):
                status, output_name, info = future.result()
                
                if status == 'skip':
                    print(f"[SKIP] {output_name} (already exists, {info} bytes)")
                    total_skipped += 1
                elif status == 'ok':
                    print(f"[OK] {output_name} ({info} bytes)")
                    total_generated += 1
                elif status == 'unknown':
                    print(f"[SKIP] {output_name} (unknown workload: {info})")
                else:
                    print(f"[ERROR] {output_name}: {info}")
                    errors.append(output_name)
    
    print("\n" + "=" * 80)
    print(f"Total QASM files generated: {total_generated}")
    print(f"Total skipped (already exist): {total_skipped}")
    if errors:
        print(f"Errors ({len(errors)}):")
        for e in errors:
            print(f"  - {e}")
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
